const PreferencesContext = createContext(null);

export function PreferencesProvider({ children }) {
  const [language, setLanguage] = useState(() => localStorage.getItem('farmfusion_language') || 'en');
  const [theme, setTheme] = useState(() => localStorage.getItem('farmfusion_theme') === 'dark' ? 'dark' : 'light');

  useEffect(() => {
    localStorage.setItem('farmfusion_language', language);
    document.documentElement.lang = language;
  }, [language]);

  useEffect(() => {
    localStorage.setItem('farmfusion_theme', theme);
    document.documentElement.dataset.theme = theme;
  }, [theme]);

  const value = useMemo(() => ({
    language,
    setLanguage,
    theme,
    setTheme,
    toggleTheme: () => setTheme((current) => current === 'dark' ? 'light' : 'dark'),
    t: (text) => translations[language]?.[text] || text,
    tProductName: (name) => productNameTranslations[language]?.[name] || name,
  }), [language, theme]);

  return <PreferencesContext.Provider value={value}>{children}</PreferencesContext.Provider>;
}

export function usePreferences() {
  const context = useContext(PreferencesContext);
  if (!context) throw new Error('usePreferences must be used within PreferencesProvider');
  return context;
}
